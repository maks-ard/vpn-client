// Package killswitch не выпускает трафик мимо VPN, пока VPN включён: если
// sing-box упал или переподключается, соединения в интернет блокируются,
// а не уходят напрямую.
//
// На Windows это фильтры WFP в динамической сессии службы. Windows сама
// удаляет их, когда сессия закрывается, в том числе при падении службы,
// поэтому оставить компьютер без интернета навсегда нельзя.
package killswitch

import "net/netip"

// Rules — что остаётся разрешённым, когда всё остальное заблокировано.
type Rules struct {
	// Apps — программы, которым можно в сеть напрямую: служба (подписка,
	// наборы правил, обновления) и sing-box (серверы VPN и трафик «напрямую»).
	// Разрешение действует только для процессов той же учётной записи, что и
	// служба, чтобы окно, запущенное из того же exe, не получило обход.
	Apps []string
	// Tunnel — адреса TUN. Соединения, которые Windows отправляет через TUN,
	// идут с этих адресов, и их разрешаем по ним: так не нужен номер
	// интерфейса, которого нет, пока sing-box не запущен.
	Tunnel []netip.Addr
}

// LAN — локальные адреса: принтеры, роутер, DHCP и NDP продолжают работать,
// пока VPN восстанавливается. DNS в локальную сеть при этом закрыт, иначе
// запросы к роутеру раскрывали бы, какие сайты открываются.
var LAN = []netip.Prefix{
	netip.MustParsePrefix("10.0.0.0/8"),
	netip.MustParsePrefix("172.16.0.0/12"),
	netip.MustParsePrefix("192.168.0.0/16"),
	netip.MustParsePrefix("169.254.0.0/16"),
	netip.MustParsePrefix("224.0.0.0/4"),
	netip.MustParsePrefix("255.255.255.255/32"),
	netip.MustParsePrefix("fc00::/7"),
	netip.MustParsePrefix("fe80::/10"),
	netip.MustParsePrefix("ff00::/8"),
}
