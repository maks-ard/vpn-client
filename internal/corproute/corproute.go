// Package corproute прокладывает в Windows маршруты через адаптер OpenVPN,
// который sing-box создаёт при openvpn.system_interface.
//
// Через адаптер идут два вида маршрутов:
//   - маршрут по умолчанию с большой метрикой. Программам он не мешает:
//     общий TUN ставит свой маршрут по умолчанию с метрикой 0. Но sing-box
//     отправляет корпоративный трафик через сокет, привязанный к адаптеру, а
//     такому сокету нужен маршрут через этот адаптер к любому адресу, иначе
//     соединение не открывается;
//   - маршруты к отдельным адресам компании. Программы, которые к ним
//     подключаются, идут мимо общего TUN, прямо через адаптер, и сервер
//     видит компьютер по адресу из пула OpenVPN, как с обычным клиентом.
//
// Маршруты живут, пока жив адаптер: когда sing-box завершается, Windows
// удаляет адаптер вместе с ними, так что убирать их не нужно.
package corproute

import "errors"

// ErrNoAdapter — адаптера ещё нет или у него ещё нет адреса IPv4:
// OpenVPN не подключился.
var ErrNoAdapter = errors.New("адаптер OpenVPN не найден")

// defaultMetric — метрика маршрута по умолчанию через адаптер: заведомо
// хуже, чем у общего TUN и физических адаптеров.
const defaultMetric = 9999
